"""Generate AI tool ignore files (.cursorignore, .copilotignore, etc.) from config."""
import os
import sys
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
import core

_HEADER = "# Generated by ai-folder-guard — https://github.com/a000a999a/ai-folder-guard\n"

_TOOL_INFO = {
    "cursor":   (".cursorignore",   "# Prevents Cursor from indexing these paths.\n"),
    "copilot":  (".copilotignore",  "# Prevents GitHub Copilot from using these files as context.\n"),
    "aider":    (".aiderignore",    "# Tells Aider not to read these files.\n"),
    "continue": (".continueignore", "# Excludes these paths from Continue context.\n"),
    "cline":    (".clineignore",    "# Excludes these paths from Cline context.\n"),
}


def write(project_dir: str, tool: str) -> str:
    cfg = core.load()
    paths = cfg.get("blocked", []) if cfg["mode"] == "blacklist" else []
    fname, note = _TOOL_INFO.get(tool, (f".{tool}ignore", ""))
    lines = [_HEADER, note] + [p + "\n" for p in paths]
    target = os.path.join(project_dir, fname)
    with open(target, "w") as f:
        f.writelines(lines)
    return target


def read(project_dir: str, tool: str) -> list:
    fname, _ = _TOOL_INFO.get(tool, (f".{tool}ignore", ""))
    target = os.path.join(project_dir, fname)
    if not os.path.exists(target):
        return []
    with open(target) as f:
        return [l.strip() for l in f if l.strip() and not l.startswith("#")]
